def review(ident):
    disposition, purpose, evidence, next_step = REVIEWS[ident]
    return dict(disposition=disposition, hardware_intent=purpose,
                reviewed_evidence=evidence, next_step=next_step,
                synthesis_qualification='结构目的；未测量面积、功耗或时序收益')
